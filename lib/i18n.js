export function getLocaleMeta(code) {
  return LOCALES.find((l) => l.code === code) || LOCALES[0];
}

export function applyLocale(code) {
  const meta = getLocaleMeta(code);
  const root = document.documentElement;
  root.lang = meta.code;
  root.dir = meta.dir;
  root.setAttribute("data-locale", meta.code);
  try {
    localStorage.setItem(STORAGE_LOCALE, meta.code);
  } catch {
    /* ignore */
  }
  return meta;
}
